import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { portableHashValue } from '../../ScriptureDiscovery/src/scripture-tree/portableRuntimeServices.mjs';
import { createProgressiveWorldProjection } from '../product-runtime/progressiveWorldProjection.mjs';
const proof = JSON.parse(fs.readFileSync('docs/01b-evidence/r2-projection-candidate.json'));
const read = d => {
  const bytes = fs.readFileSync(path.join(proof.output, `${d.sha256}.json`));
  assert.equal(bytes.length, d.bytes); assert.equal(createHash('sha256').update(bytes).digest('hex'), d.sha256);
  return JSON.parse(bytes);
};
const locator = read(proof.locator), requests = [];
const config = { revision: proof.revision, governedWorldHash: proof.governedWorldHash, acceptedRootIndexHash: proof.rootProjectionProof[0].acceptedRootIndexHash, locator, hashValue: portableHashValue };
const runtime = createProgressiveWorldProjection({ ...config, transport: { load: async d => { requests.push(d.sha256); return read(d); } } });
const root = await runtime.open('character:abraham');
assert.equal(requests.length, 2); assert.equal(root.diagnostics().installedReferences, 0);
assert.equal(root.projection.identity.semanticHash, proof.rootProjectionProof[0].acceptedRootSemanticHash);
const selected = root.projection.orderedDependencyRefs.find(ref => ref.startsWith('scene:'));
assert.ok(selected); assert.throws(() => root.readReference(selected), /ACQUISITION_REQUIRED/);
await Promise.all(Array.from({ length: 10 }, () => root.ensureReference(selected)));
assert.equal(requests.length, 3); assert.equal(root.diagnostics().installedReferences, 1);
assert.equal(await runtime.open('character:abraham'), root);
await root.ensureReference(selected); assert.equal(requests.length, 3);
await assert.rejects(root.ensureReference('scene:unknown'), /REF_NOT_OWNED/);
const bad = createProgressiveWorldProjection({ ...config, acceptedRootIndexHash: '0'.repeat(64), transport: { load: async d => read(d) } });
await assert.rejects(bad.open('character:abraham'), /PROJECTION_BINDING/);
const corrupted = createProgressiveWorldProjection({ ...config, transport: { load: async d => { const value = read(d); if (value.projectionHash) value.identity.semanticHash = '0'.repeat(64); return value; } } });
await assert.rejects(corrupted.open('character:abraham'), /PROJECTION_BINDING/);
const report = { status: 'PASS', scope: 'ROOT_PROJECTION_INTEGRITY_NOT_WORLD_UI_ACCEPTANCE', revision: proof.revision, rootEntryBytes: proof.abraham.bytes, projectionManifestBytes: proof.rootProjectionProof[0].projectionManifest.bytes, coldRootMetadataPackets: 2, descendantBodiesHydratedAtEntry: 0, chapterPacketsRequested: 0, selectedDescriptorRequests: 1, repeatedDescriptorRequests: 0, acceptedEnrichedRootBinding: 'PASS', mismatchedRootIndexRejected: true, tamperedProjectionRejected: true, nativeWorldKernelIntegrated: false };
fs.writeFileSync('docs/01b-evidence/r2a-root-projection.json', JSON.stringify(report,null,2)+'\n'); console.log(report);
