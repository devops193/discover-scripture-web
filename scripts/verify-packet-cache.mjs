import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import { createPacketCache } from '../product-runtime/packetCache.mjs';
const revision = 'a'.repeat(64), baseUrl = 'https://packets.invalid/sdw/';
const bytes = Buffer.from(JSON.stringify({ identity: 'test:GEN:22', classification: 'TRANSPORT_TEST_ONLY' }));
const sha256 = createHash('sha256').update(bytes).digest('hex');
const descriptor = { revision, sha256, bytes: bytes.length, url: `${baseUrl}${sha256}.json` };
const stores = new Map();
const cacheStorage = { async open(name) {
  if (!stores.has(name)) stores.set(name, new Map()); const data = stores.get(name);
  return { async match(key) { return data.get(key)?.clone(); }, async put(key, response) { data.set(key, response.clone()); }, async delete(key) { return data.delete(key); } };
} };
let requests = 0;
const fetchResource = async () => { requests++; return new Response(bytes); };
const create = (options = {}) => createPacketCache({ revision, baseUrl, cacheStorage, fetchResource, ...options });
const first = create();
await Promise.all(Array.from({ length: 20 }, () => first.load(descriptor)));
assert.equal(requests, 1);
const warm = create(); await warm.load(descriptor); assert.equal(requests, 1);
assert.equal(warm.diagnostics().cacheHits, 1);
await assert.rejects(() => warm.load({ ...descriptor, revision: 'b'.repeat(64) }), /INVALID_PACKET_DESCRIPTOR/);
await assert.rejects(() => warm.load({ ...descriptor, url: `https://other.invalid/${sha256}.json` }), /INVALID_PACKET_URL/);
assert.equal(requests, 1);
const next = create({ revision: 'b'.repeat(64) }); await next.load({ ...descriptor, revision: 'b'.repeat(64) }); assert.equal(requests, 2);
const store = await cacheStorage.open(`sdw-packets-v1-${revision}`);
await store.put(descriptor.url, new Response('corrupt'));
await assert.rejects(() => warm.load(descriptor), /PACKET_INTEGRITY/);
assert.equal(requests, 2); assert.equal(await store.match(descriptor.url), undefined);
const bad = create({ fetchResource: async () => new Response('invalid') });
await assert.rejects(() => bad.load(descriptor), /PACKET_INTEGRITY/);
assert.equal(await store.match(descriptor.url), undefined);
const report = { status: 'PASS', scope: 'DETERMINISTIC_ADAPTER_TEST_NOT_BROWSER_OR_APP_ACCEPTANCE', parallelRequests: 20, initialNetworkRequests: 1, newInstanceWarmNetworkRequests: 0, crossRevisionIsolation: 'PASS', corruptCacheRejectedWithoutNetworkFallback: 'PASS', corruptDownloadNotPersisted: 'PASS', authority: 'NO_SEMANTIC_AUTHORITY' };
fs.writeFileSync('docs/01b-evidence/r2-packet-cache-tests.json', JSON.stringify(report, null, 2) + '\n');
console.log(report);
